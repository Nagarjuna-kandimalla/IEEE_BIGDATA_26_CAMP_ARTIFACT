#!/usr/bin/env python3
"""Route only this running cold workflow's task submissions to validated workers."""
import fcntl, json, os, re, subprocess, sys, time
from pathlib import Path

root = Path(os.environ["CAMP_RQ5_LIVE_ROOT"]).resolve()
settings = json.loads((root / "experiments/plan.json").read_text())["settings"]
label = os.environ.get("CAMP_RUN_ID", "")
run = root / "live/runs" / label
args = sys.argv[1:]
cwd = Path.cwd().resolve()
if label in json.loads((root / "experiments/plan.json").read_text())[
    "registered_run_ids"
] and cwd.is_relative_to(run / "work"):
    while (root / "deployment/retry-reload.pause").exists():
        time.sleep(1)
    candidates = [
        (i, Path(a))
        for i, a in enumerate(args)
        if Path(a).name == ".command.run" and Path(a).is_file()
    ]
    if len(candidates) == 1:
        index, source = candidates[0]
        text = source.read_text()
        lines = [
            (
                line.replace("--nodelist=" + settings["controller_node"], "")
                if line.startswith("#SBATCH")
                else line
            )
            for line in text.splitlines(keepends=True)
        ]
        # Inject only the post-readiness health guard into scripts already
        # generated by the running JVM; task commands and decisions are intact.
        if "resume_watch_pid" not in text:
            guard = r"""(
          while kill -0 "$task_pid" 2>/dev/null; do
            local_state=
            while read -r key value rest; do
              if [[ "$key" == State: ]]; then local_state=$value; break; fi
            done < "/proc/$task_pid/status" 2>/dev/null || true
            if [[ "$local_state" == T || "$local_state" == t ]]; then
              kill -CONT "$task_pid" 2>/dev/null || true
            fi
            sleep 0.25
          done
        ) &
        local resume_watch_pid=$!
        """
            joined = "".join(lines)
            if (
                "local task_status=0" in joined
                and 'wait "$task_pid" || task_status=$?' in joined
            ):
                joined = re.sub(
                    r'(?m)^(\s*)kill -CONT "\$task_pid"\n(\s*)local resume_confirmed=false',
                    lambda match: guard + match.group(0),
                    joined,
                    count=1,
                )
                joined = joined.replace(
                    'wait "$task_pid" || task_status=$?',
                    'wait "$task_pid" || task_status=$?\n        kill "$resume_watch_pid" 2>/dev/null || true\n        wait "$resume_watch_pid" 2>/dev/null || true',
                    1,
                )
                lines = joined.splitlines(keepends=True)
        # Wait for termination, rather than a stopped-child status change.
        lines = (
            "".join(lines)
            .replace(
                'wait "$task_pid" || task_status=$?',
                'wait -f "$task_pid" || task_status=$?',
            )
            .splitlines(keepends=True)
        )
        routed = cwd / ".command.worker.run"
        temporary = routed.with_suffix(".tmp")
        temporary.write_text("".join(lines))
        temporary.chmod(source.stat().st_mode)
        temporary.replace(routed)
        args[index] = str(routed)
        workers = settings["workers"]
        while True:
            if (root / "deployment/retry-reload.pause").exists():
                time.sleep(1)
                continue
            listing = subprocess.check_output(
                ["/usr/bin/squeue", "-h", "-t", "PD,R,CF,CG,S", "-o", "%i|%n|%N|%T|%Z"],
                text=True,
            )
            counts = {worker: 0 for worker in workers}
            for line in listing.splitlines():
                fields = line.split("|", 4)
                if len(fields) != 5:
                    continue
                _, requested, allocated, state, working_directory = fields
                if state not in {
                    "PENDING",
                    "RUNNING",
                    "CONFIGURING",
                    "COMPLETING",
                    "SUSPENDED",
                }:
                    continue
                if not working_directory.startswith(str(run / "work") + "/"):
                    continue
                node = requested or allocated
                if node in counts:
                    counts[node] += 1
            available = [
                w for w in workers if counts[w] < settings["per_worker_task_admission"]
            ]
            if available:
                worker = min(available, key=lambda w: (counts[w], w))
                break
            time.sleep(0.5)
        allowance_path = root / "deployment/execution-memory-allowance.json"
        allowance = 128
        if allowance not in (0, 128):
            raise RuntimeError("Unexpected execution-memory allowance")
        grant = None
        if allowance:
            memories = re.findall(
                r"^#SBATCH\s+--mem(?:=|\s+)([0-9]+)M\s*$", text, re.MULTILINE
            )
            if len(memories) != 1:
                raise RuntimeError("Cannot identify original CAMP memory grant")
            predicted = int(memories[0])
            actual = predicted + allowance
            grant = {
                "camp_prediction_mib": predicted,
                "execution_allowance_mib": allowance,
                "actual_slurm_grant_mib": actual,
                "time": time.time(),
                "work_dir": str(cwd),
            }
            grant_path = cwd / ".execution-memory-grant.json"
            temp = grant_path.with_suffix(".tmp")
            temp.write_text(json.dumps(grant, indent=2) + "\n")
            temp.replace(grant_path)
            args = ["--mem=" + str(actual) + "M", *args]
        args = [
            "--partition=" + settings["task_partition"],
            "--nodelist=" + worker,
            *args,
        ]
        with (root / "deployment/worker-routing.jsonl").open("a") as f:
            f.write(
                json.dumps(
                    {
                        "time": time.time(),
                        "work_dir": str(cwd),
                        "script": str(routed),
                        "partition": settings["task_partition"],
                        "worker": worker,
                    }
                )
                + "\n"
            )
os.execv("/usr/bin/sbatch", ["/usr/bin/sbatch", *args])
